#!/usr/bin/env python3
"""Generate GitHub issue and pull-request templates from `.ai/templates/`.

`.ai/` is the canonical source. The files under `.github/` are generated
copies with GitHub front matter added, and must not be edited by hand.

Usage:
    python3 tools/generate_github_templates.py            # write the files
    python3 tools/generate_github_templates.py --check    # fail on drift
    python3 tools/generate_github_templates.py --root DIR [--check]

`--check` exits 0 when every generated file matches its source, and 1 (with
the stale file names) when any file is missing or differs.
"""

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

GENERATOR_PATH = "tools/generate_github_templates.py"
DEFAULT_ROOT = Path(__file__).resolve().parents[1]

REQUIRED_PULL_REQUEST_SECTIONS = (
    "Card",
    "Summary",
    "Scope check",
    "Reuse and cost",
    "Traceability",
    "Test evidence",
    "Security",
    "Preview",
    "Residual risks",
)

FRONT_MATTER_PATTERN = re.compile(r"\A---\n.*?\n---\n\n?", re.DOTALL)
GENERATED_HEADER_PATTERN = re.compile(r"\A<!-- Generated from .*? -->\n\n", re.DOTALL)


class TemplateSourceError(Exception):
    """A canonical source template breaks a rule the generated file relies on."""


@dataclass(frozen=True)
class GeneratedTemplate:
    source: str
    target: str
    front_matter: dict = field(default_factory=dict)
    required_sections: tuple = ()


TEMPLATES = (
    GeneratedTemplate(
        source=".ai/templates/implementation-card.md",
        target=".github/ISSUE_TEMPLATE/implementation-card.md",
        front_matter={
            "name": "Implementation card",
            "about": "One small, test-first change. Must pass tools/validate_card.py before Ready.",
            "title": "<CARD-ID> — <outcome>",
            "labels": ["card"],
        },
    ),
    GeneratedTemplate(
        source=".ai/templates/user-story.md",
        target=".github/ISSUE_TEMPLATE/user-story.md",
        front_matter={
            "name": "User story",
            "about": "A user need for the Inbox. The architect turns it into implementation cards.",
            "title": "<user outcome>",
            "labels": ["user-story"],
        },
    ),
    GeneratedTemplate(
        source=".ai/templates/pull-request.md",
        target=".github/pull_request_template.md",
        required_sections=REQUIRED_PULL_REQUEST_SECTIONS,
    ),
)

ISSUE_CONFIG_TARGET = ".github/ISSUE_TEMPLATE/config.yml"
ISSUE_CONFIG_CONTENT = (
    f"# Generated by {GENERATOR_PATH}. Do not edit; change the generator and regenerate.\n"
    "# Every issue must start from a template so cards stay validatable.\n"
    "blank_issues_enabled: false\n"
)


def render_front_matter(fields):
    if not fields:
        return ""
    lines = ["---"]
    for key, value in fields.items():
        if isinstance(value, list):
            rendered = "[" + ", ".join(quote(item) for item in value) + "]"
        else:
            rendered = quote(value)
        lines.append(f"{key}: {rendered}")
    lines.append("---")
    return "\n".join(lines) + "\n\n"


def quote(value):
    # Double-quoted YAML strings: escape backslashes and quotes only.
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def generated_header(source):
    return (
        f"<!-- Generated from {source} by {GENERATOR_PATH}. "
        "Do not edit; change the source and regenerate. -->\n\n"
    )


def strip_front_matter(text):
    return FRONT_MATTER_PATTERN.sub("", text, count=1)


def strip_generated_header(text):
    return GENERATED_HEADER_PATTERN.sub("", strip_front_matter(text), count=1)


def check_required_sections(template, source_text):
    present = set(re.findall(r"^##\s+(.+?)\s*$", source_text, re.MULTILINE))
    missing = [name for name in template.required_sections if name not in present]
    if missing:
        raise TemplateSourceError(
            f"{template.source} is missing required section(s): {', '.join(missing)}"
        )


def expected_files(root):
    """Return {relative target path: expected content}."""
    root = Path(root)
    expected = {}
    for template in TEMPLATES:
        source_text = (root / template.source).read_text(encoding="utf-8")
        check_required_sections(template, source_text)
        expected[template.target] = (
            render_front_matter(template.front_matter)
            + generated_header(template.source)
            + source_text
        )
    expected[ISSUE_CONFIG_TARGET] = ISSUE_CONFIG_CONTENT
    return expected


def write_all(root):
    root = Path(root)
    for relative_path, content in expected_files(root).items():
        target = root / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")


def find_stale_files(root):
    root = Path(root)
    stale = []
    for relative_path, content in expected_files(root).items():
        target = root / relative_path
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            stale.append(relative_path)
    return sorted(stale)


def main(arguments):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if files are stale")
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    options = parser.parse_args(arguments)

    try:
        if options.check:
            stale = find_stale_files(options.root)
            for relative_path in stale:
                print(f"STALE: {relative_path} (run {GENERATOR_PATH})")
            if not stale:
                print("OK: GitHub templates match .ai/templates/")
            return 1 if stale else 0
        write_all(options.root)
    except TemplateSourceError as source_error:
        print(f"ERROR: {source_error}")
        return 1
    print(f"Wrote GitHub templates under {options.root / '.github'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
